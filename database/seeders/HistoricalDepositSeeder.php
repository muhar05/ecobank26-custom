    public function run(): void
    {
        $customers = WasteCustomer::all()->keyBy('name');
        $categories = WasteCategory::all()->keyBy('name');
        $bank = app(BankSampahService::class);

        $created = 0;
        $skipped = 0;

        DB::transaction(function () use ($customers, $categories, $bank, &$created, &$skipped) {
            foreach (self::deposits() as $item) {
                $customer = $customers->get($item['c']);
                if (! $customer) {
                    $this->command?->warn("Setoran dilewati: nasabah '{$item['c']}' tidak ditemukan.");
                    $skipped++;

                    continue;
                }

                $exists = Deposit::where('waste_customer_id', $customer->id)
                    ->whereDate('date', $item['d'])
                    ->exists();
                if ($exists) {
                    $skipped++;

                    continue;
                }

                $details = [];
                foreach ($item['x'] as $row) {
                    $category = isset($row['cat']) ? $categories->get($row['cat']) : null;

                    if (! $category && ! isset($row['label'])) {
                        throw new \RuntimeException("Kategori '{$row['cat']}' tidak ditemukan saat seed setoran. Jalankan HistoricalMasterDataSeeder lebih dulu.");
                    }

                    $details[] = [
                        'waste_category_id' => $category?->id,
                        'material_label' => $category ? null : ($row['label'] ?? null),
                        'weight' => $row['w'],
                        'price_per_unit' => $row['p'],
                        'subtotal' => $row['t'],
                    ];
                }

                $bank->recordDeposit([
                    'waste_customer_id' => $customer->id,
                    'date' => $item['d'],
                    'notes' => 'Historical import (Sheet: ' . $item['s'] . ')',
                    'details' => $details,
                ]);

                $created++;
            }
        });

        $this->command?->info("Setoran historis berhasil disinkronkan: {$created} setoran baru, {$skipped} dilewati.");
    }
